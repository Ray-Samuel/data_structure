#include <stdio.h>

// INTEIROS
void leiaInt(int *var){
  scanf("%d", var);
}
void imprimaInt(int var){
  printf("%d", var);
}

// REAIS
void leiaFloat(float *var){
  scanf("%f", var);
}
void imprimaFloat(float var){
  printf("%2.f", var);
}

// CARACTERES
void leiaChar(char *var){
  scanf("%f", var);
}
void imprimaChar(char var){
  printf("%2.f", var);
}
